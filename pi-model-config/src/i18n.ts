export function t(language: UiLanguage, key: TranslationKey, params?: TranslationParams): string {
  let message: string = STRINGS[language][key];
  for (const [name, value] of Object.entries(params ?? {})) message = message.split(`{${name}}`).join(String(value));
  return message;
}

