export class ModelConfigError extends Error {
  constructor(public readonly code: ErrorCode, public readonly params: TranslationParams = {}, options?: ErrorOptions) {
    super(code, options);
    this.name = "ModelConfigError";
  }
}

export function mcError(code: ErrorCode, params: TranslationParams = {}, cause?: unknown): ModelConfigError {
  return new ModelConfigError(code, params, cause === undefined ? undefined : { cause });
}

export function formatError(language: UiLanguage, error: unknown, safeExternalDetail?: string): string {
  if (error instanceof ModelConfigError) {
    const template = language === "zh-CN" ? ERROR_ZH[error.code] : ERROR_EN[error.code];
    let message = template;
    for (const [name, value] of Object.entries(error.params)) message = message.split(`{${name}}`).join(String(value));
    return `[${error.code}] ${message}`;
  }
  return t(language, "errorExternal", {
    code: "MCFG_E_EXTERNAL",
    detail: safeExternalDetail?.trim() || t(language, "errorUnknownDetail"),
  });
}
